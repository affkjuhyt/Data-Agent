"""The DS-AW document seed is what worker-document makes of the files it registers.

deploy/docker/sql/v3-adventureworks-documents.sql is generated by tests/e2e/adventureworks/
documents.py from deploy/docker/adventureworks-docs/ with this service's extractor, mask and
chunker. A changed file, a changed pipeline or a hand edit of the seed leaves pages that the
worker would not have written: regenerate with `make adventureworks-documents`.
"""

from __future__ import annotations

import importlib.util
import pathlib
import sys

import pytest

from services.worker_document.validity import find_replacements

pytestmark = pytest.mark.unit

ROOT = pathlib.Path(__file__).resolve().parents[3]
_spec = importlib.util.spec_from_file_location(
    "adventureworks_documents", ROOT / "tests" / "e2e" / "adventureworks" / "documents.py"
)
assert _spec and _spec.loader
documents = importlib.util.module_from_spec(_spec)
# dataclasses look their module up in sys.modules.
sys.modules[_spec.name] = documents
_spec.loader.exec_module(documents)


def _pages(doc_no: str) -> list[str]:
    doc = next(d for d in documents.DOCUMENTS if d.doc_no == doc_no)
    return [text for _, text, _, _ in documents.process(doc).pages]


def test_the_seed_is_what_the_worker_makes_of_the_files() -> None:
    assert (
        documents.SEED.read_text(encoding="utf-8") == documents.sql()
    ), "v3-adventureworks-documents.sql is stale: run make adventureworks-documents"


def test_every_file_is_registered_once() -> None:
    files = sorted(p for p in documents.FILES.rglob("*") if p.is_file())
    assert sorted(documents.path(d) for d in documents.DOCUMENTS) == files
    assert len({d.doc_no for d in documents.DOCUMENTS}) == len(documents.DOCUMENTS)


def test_every_replaced_document_ends_before_its_replacement_starts() -> None:
    by_no = {d.doc_no: d for d in documents.DOCUMENTS}
    replaced = [(by_no[d.supersedes], d) for d in documents.DOCUMENTS if d.supersedes]
    assert len(replaced) == 2
    for old, new in replaced:
        assert old.effective_to is not None and old.effective_to < new.effective_from


def test_the_vietnamese_replacement_is_detected() -> None:
    found = find_replacements(_pages("07/2012/QĐ-AWC"))
    assert [r.doc_no for r in found] == ["01/2011/QĐ-AWC"]


def test_a_mention_of_another_document_is_not_a_replacement() -> None:
    # The final report and the call-centre procedure cite other documents without replacing them.
    assert find_replacements(_pages("09/2013/BC-AWC")) == []
    assert find_replacements(_pages("05/2014/QT-AWC")) == []


@pytest.mark.xfail(
    strict=True,
    reason="validity._REPLACES reads only the Vietnamese 'thay thế ...': an English 'This policy "
    "supersedes Policy No. ...' proposes no link, so the seed's link is a person's",
)
def test_the_english_supersedes_is_detected() -> None:
    found = find_replacements(_pages("10/2013/POL-AWC"))
    assert [r.doc_no for r in found] == ["06/2011/POL-AWC"]
