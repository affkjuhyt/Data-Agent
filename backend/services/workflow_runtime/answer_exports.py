"""Answer table export artifacts for the Ask UI.

The chat stream carries only a preview of SQL rows. Full rows and the Excel
workbook live behind authenticated workflow_runtime routes, keyed by tenant and
an opaque result id instead of a client-supplied object key.
"""
from __future__ import annotations

import asyncio
import io
import json
import logging
import os
import re
import uuid
from datetime import datetime, timezone
from typing import Any

logger = logging.getLogger(__name__)

BUCKET = os.getenv("ANSWER_EXPORT_BUCKET", "answer-exports")
_RESULT_ID_RE = re.compile(r"^[a-f0-9]{32}$")
_MAX_SHEET_ROWS = int(os.getenv("ANSWER_EXPORT_MAX_XLSX_ROWS", "100000"))


def _s3_client() -> Any:
    import boto3

    return boto3.client(
        "s3",
        endpoint_url=os.getenv("MINIO_ENDPOINT", "http://minio:9000"),
        aws_access_key_id=os.getenv("MINIO_ACCESS_KEY", "minio"),
        aws_secret_access_key=os.getenv("MINIO_SECRET_KEY", "minio_secret"),
    )


def _prefix(tenant_id: str, result_id: str) -> str:
    if not _RESULT_ID_RE.match(result_id):
        raise ValueError("invalid result id")
    return f"tenant/{tenant_id}/ask-results/{result_id}"


def _json_default(value: Any) -> str:
    if isinstance(value, datetime):
        return value.isoformat()
    return str(value)


def _safe_cell(value: Any) -> Any:
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    return json.dumps(value, ensure_ascii=False, default=_json_default)


def _source_rows(run: dict[str, Any], question: str) -> list[tuple[str, Any]]:
    metric = run.get("metric") if isinstance(run.get("metric"), dict) else {}
    provenance = run.get("provenance") if isinstance(run.get("provenance"), dict) else {}
    aggregation = run.get("aggregation") if isinstance(run.get("aggregation"), dict) else {}
    truncation = run.get("truncation") if isinstance(run.get("truncation"), dict) else {}
    tables = provenance.get("tables") if isinstance(provenance.get("tables"), list) else []
    return [
        ("Question", question),
        ("Exported at", datetime.now(timezone.utc).isoformat()),
        ("Run id", run.get("id") or ""),
        ("Database", run.get("db_name") or ""),
        ("Database type", run.get("db_type") or ""),
        ("Generated by", run.get("generated_by") or ""),
        ("Rows returned", run.get("row_count") or len(run.get("rows") or [])),
        ("SQL", run.get("sql") or ""),
        ("Metric", metric.get("metric") or ""),
        ("Matched term", metric.get("matched_term") or ""),
        ("Definition", metric.get("definition") or ""),
        ("Aggregation", metric.get("aggregation") or ""),
        ("Unit", metric.get("unit") or ""),
        ("Grain", metric.get("grain") or ""),
        ("Business date column", metric.get("business_date_column") or ""),
        ("Owner", metric.get("owner") or ""),
        ("Freshness status", provenance.get("status") or ""),
        ("Data as of", provenance.get("as_of") or ""),
        ("Classification", provenance.get("classification") or ""),
        ("Owners", ", ".join(provenance.get("owners") or [])),
        ("Tables", ", ".join(str(t.get("table", "")) for t in tables if isinstance(t, dict))),
        ("Stale tables", ", ".join(provenance.get("stale_tables") or [])),
        ("Unknown tables", ", ".join(provenance.get("unknown_tables") or [])),
        ("Truncation", json.dumps(truncation, ensure_ascii=False, default=_json_default) if truncation else ""),
        ("Aggregation check", json.dumps(aggregation, ensure_ascii=False, default=_json_default) if aggregation else ""),
    ]


def build_xlsx(run: dict[str, Any], question: str) -> bytes:
    """Create an .xlsx workbook with Data and Nguồn sheets."""
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.utils import get_column_letter

    columns = [str(c) for c in run.get("columns") or []]
    rows = [r for r in run.get("rows") or [] if isinstance(r, dict)]

    wb = Workbook()
    ws = wb.active
    ws.title = "Dữ liệu"
    header_fill = PatternFill("solid", fgColor="111111")
    header_font = Font(color="FFFFFF", bold=True)

    ws.append(columns)
    for cell in ws[1]:
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(vertical="center")

    for row in rows[:_MAX_SHEET_ROWS]:
        ws.append([_safe_cell(row.get(c)) for c in columns])

    ws.freeze_panes = "A2"
    ws.auto_filter.ref = ws.dimensions
    for idx, column in enumerate(columns, start=1):
        width = min(max(len(column) + 2, 12), 48)
        ws.column_dimensions[get_column_letter(idx)].width = width

    src = wb.create_sheet("Nguồn")
    src.append(["Trường", "Giá trị"])
    for cell in src[1]:
        cell.fill = header_fill
        cell.font = header_font
    for key, value in _source_rows(run, question):
        src.append([key, _safe_cell(value)])
    src.column_dimensions["A"].width = 24
    src.column_dimensions["B"].width = 96
    for row in src.iter_rows(min_row=2, min_col=2, max_col=2):
        row[0].alignment = Alignment(wrap_text=True, vertical="top")

    bio = io.BytesIO()
    wb.save(bio)
    return bio.getvalue()


def _put_object(client: Any, key: str, body: bytes, content_type: str) -> None:
    client.put_object(Bucket=BUCKET, Key=key, Body=body, ContentType=content_type)


def _ensure_bucket(client: Any) -> None:
    if not hasattr(client, "head_bucket") or not hasattr(client, "create_bucket"):
        return
    try:
        client.head_bucket(Bucket=BUCKET)
    except Exception as e:  # noqa: BLE001 - boto/minio-compatible fakes vary
        code = getattr(e, "response", {}).get("Error", {}).get("Code", "")
        if code in ("404", "NoSuchBucket", "NotFound"):
            client.create_bucket(Bucket=BUCKET)
            return
        raise


def _get_object(client: Any, key: str) -> bytes:
    resp = client.get_object(Bucket=BUCKET, Key=key)
    return resp["Body"].read()


async def create_answer_export(run: dict[str, Any], *, tenant_id: str, question: str) -> dict[str, Any] | None:
    """Persist full rows + workbook for one SQL run; never fail the answer."""
    if not tenant_id or not run.get("columns") or not run.get("rows"):
        return None

    result_id = uuid.uuid4().hex
    prefix = _prefix(tenant_id, result_id)
    payload = {
        "result_id": result_id,
        "question": question,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "columns": run.get("columns") or [],
        "rows": run.get("rows") or [],
        "source": {k: v for k, v in run.items() if k != "rows"},
    }
    payload_bytes = json.dumps(payload, ensure_ascii=False, default=_json_default).encode("utf-8")

    try:
        xlsx = await asyncio.to_thread(build_xlsx, run, question)
        client = _s3_client()
        await asyncio.to_thread(_ensure_bucket, client)
        await asyncio.to_thread(_put_object, client, f"{prefix}/payload.json", payload_bytes, "application/json; charset=utf-8")
        await asyncio.to_thread(
            _put_object,
            client,
            f"{prefix}/answer.xlsx",
            xlsx,
            "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        )
    except Exception as e:  # noqa: BLE001 - export is optional, answer must still stream
        logger.warning("answer_export | disabled for run=%s: %s", run.get("id"), e)
        return None

    return {
        "result_id": result_id,
        "preview_rows": min(len(run.get("rows") or []), 100),
        "total_rows": len(run.get("rows") or []),
        "full_available": True,
        "xlsx_available": True,
        "file_name": f"ask-result-{result_id[:8]}.xlsx",
        "sheets": ["Dữ liệu", "Nguồn"],
    }


async def load_payload(tenant_id: str, result_id: str) -> dict[str, Any]:
    try:
        key = f"{_prefix(tenant_id, result_id)}/payload.json"
        data = await asyncio.to_thread(_get_object, _s3_client(), key)
        payload = json.loads(data.decode("utf-8"))
        if not isinstance(payload, dict):
            raise ValueError("payload is not an object")
        return payload
    except ValueError:
        raise
    except Exception as e:  # noqa: BLE001 - storage clients differ in tests/runtime
        raise FileNotFoundError(str(e)) from e


async def load_xlsx(tenant_id: str, result_id: str) -> bytes:
    try:
        key = f"{_prefix(tenant_id, result_id)}/answer.xlsx"
        return await asyncio.to_thread(_get_object, _s3_client(), key)
    except ValueError:
        raise
    except Exception as e:  # noqa: BLE001 - storage clients differ in tests/runtime
        raise FileNotFoundError(str(e)) from e
