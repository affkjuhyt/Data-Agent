#!/usr/bin/env bash
# Fills deploy/k8s/secrets.env (git-ignored) from deploy/k8s/secrets.env.example
# with random values, once. Re-running never rotates an existing value — same
# "generate once, persist" pattern.
#
# OPENBAO_TOKEN / OPENBAO_ROLE_ID / OPENBAO_SECRET_ID are left blank here —
# bootstrap-openbao.sh mints them after OpenBao is actually running and
# rewrites just those three lines in place.
#
#   bash deploy/k8s/gen-secrets-env.sh
#   set -a; . deploy/k8s/secrets.env; set +a
#   bash deploy/k8s/create-secrets.sh
set -euo pipefail
cd "$(dirname "$0")"

OUT="${SECRETS_ENV:-secrets.env}"
NODE_IP="${NODE_IP:-$(hostname -I | awk '{print $1}')}"

rand() { openssl rand -hex "${1:-20}"; }

if [[ -f "$OUT" ]]; then
  echo "$OUT already exists — leaving it alone (delete it to regenerate)."
  exit 0
fi

POSTGRES_PASSWORD="$(rand)"
KEYCLOAK_ADMIN_PASSWORD="$(rand)"
MINIO_ROOT_USER="minioadmin"
MINIO_ROOT_PASSWORD="$(rand)"
NEO4J_PASSWORD="$(rand)"
CLICKHOUSE_USER="langfuse"
CLICKHOUSE_PASSWORD="$(rand)"
GRAFANA_ADMIN_PASSWORD="$(rand)"
GATEWAY_KEY="$(rand)"
SERVICE_AUTH_SECRET="$(rand)"
KAFKA_ADMIN_PASSWORD="$(rand)"
AUDIT_CONSUMER_KAFKA_PASSWORD="$(rand)"
WORKFLOW_RUNTIME_KAFKA_PASSWORD="$(rand)"
MEMORY_CONSUMER_KAFKA_PASSWORD="$(rand)"
SCHEMA_CRAWLER_WORKER_KAFKA_PASSWORD="$(rand)"
LITELLM_API_KEY="sk-$(rand 16)"
LANGFUSE_SALT="$(rand)"
LANGFUSE_ENCRYPTION_KEY="$(openssl rand -hex 32)"   # must be exactly 32 bytes hex
LANGFUSE_NEXTAUTH_SECRET="$(rand)"
LANGFUSE_PUBLIC_KEY="pk-lf-$(rand 8)"
LANGFUSE_SECRET_KEY="sk-lf-$(rand 8)"
LANGFUSE_INIT_PASSWORD="$(rand)"

# Public URLs: NodePort, no ingress controller on this single-node cluster
# (see service/kong.yaml, service/keycloak.yaml, service/frontend.yaml).
KEYCLOAK_PUBLIC_URL="http://$NODE_IP:30110"
PUBLIC_API_URL="http://$NODE_IP:30100"
LANGFUSE_PUBLIC_URL="http://$NODE_IP:30420"

cat > "$OUT" <<EOF
# Generated by gen-secrets-env.sh on $(date -u +%FT%TZ). git-ignored.
AUDIT_CONSUMER_KAFKA_PASSWORD=$AUDIT_CONSUMER_KAFKA_PASSWORD
CLICKHOUSE_CRAWLER_PASSWORD=
CLICKHOUSE_PASSWORD=$CLICKHOUSE_PASSWORD
CLICKHOUSE_USER=$CLICKHOUSE_USER
DATABASE_URL=postgresql://admin:$POSTGRES_PASSWORD@postgres.dataagent-database.svc.cluster.local:8300/dataagent
EVAL_AGENT_ID=
GATEWAY_KEY=$GATEWAY_KEY
GEMINI_API_KEY=
GRAFANA_ADMIN_PASSWORD=$GRAFANA_ADMIN_PASSWORD
KAFKA_ADMIN_PASSWORD=$KAFKA_ADMIN_PASSWORD
KEYCLOAK_ADMIN=admin
KEYCLOAK_ADMIN_PASSWORD=$KEYCLOAK_ADMIN_PASSWORD
KEYCLOAK_PUBLIC_URL=$KEYCLOAK_PUBLIC_URL
LANGFUSE_DATABASE_URL=postgresql://admin:$POSTGRES_PASSWORD@postgres.dataagent-database.svc.cluster.local:8300/langfuse
LANGFUSE_ENCRYPTION_KEY=$LANGFUSE_ENCRYPTION_KEY
LANGFUSE_INIT_EMAIL=admin@example.com
LANGFUSE_INIT_PASSWORD=$LANGFUSE_INIT_PASSWORD
LANGFUSE_NEXTAUTH_SECRET=$LANGFUSE_NEXTAUTH_SECRET
LANGFUSE_PUBLIC_KEY=$LANGFUSE_PUBLIC_KEY
LANGFUSE_PUBLIC_URL=$LANGFUSE_PUBLIC_URL
LANGFUSE_SALT=$LANGFUSE_SALT
LANGFUSE_SECRET_KEY=$LANGFUSE_SECRET_KEY
LITELLM_API_KEY=$LITELLM_API_KEY
LITELLM_DATABASE_URL=postgresql://admin:$POSTGRES_PASSWORD@postgres.dataagent-database.svc.cluster.local:8300/litellm
MEMORY_CONSUMER_KAFKA_PASSWORD=$MEMORY_CONSUMER_KAFKA_PASSWORD
MINIO_ROOT_PASSWORD=$MINIO_ROOT_PASSWORD
MINIO_ROOT_USER=$MINIO_ROOT_USER
MINIO_URL=http://$MINIO_ROOT_USER:$MINIO_ROOT_PASSWORD@minio.dataagent-database.svc.cluster.local:8360
# libs/database_connector/neo4j_connector.py calls
# AsyncGraphDatabase.driver(uri=...) with no auth= — it only works against an
# unauthenticated server. Real auth needs that connector fixed first.
NEO4J_AUTH=none
OPENAI_API_KEY=
OPENBAO_ROLE_ID=
OPENBAO_SECRET_ID=
OPENBAO_TOKEN=
PGPASSWORD=$POSTGRES_PASSWORD
POSTGRES_CRAWLER_PASSWORD=
POSTGRES_DSN=postgresql://admin:$POSTGRES_PASSWORD@postgres.dataagent-database.svc.cluster.local:8300/dataagent
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
POSTGRES_URL_ASYNC=postgresql+asyncpg://admin:$POSTGRES_PASSWORD@postgres.dataagent-database.svc.cluster.local:8300/dataagent
PUBLIC_API_URL=$PUBLIC_API_URL
REMOTE_API_KEY=
REMOTE_LLM_KEY=
RUNTIME_DB_URL=postgresql+asyncpg://runtime_writer:runtime_dev_pw@postgres.dataagent-database.svc.cluster.local:8300/dataagent
SCHEMA_CRAWLER_WORKER_KAFKA_PASSWORD=$SCHEMA_CRAWLER_WORKER_KAFKA_PASSWORD
SERVICE_AUTH_SECRET=$SERVICE_AUTH_SECRET
SNOWFLAKE_CRAWLER_PASSWORD=
WORKFLOW_RUNTIME_KAFKA_PASSWORD=$WORKFLOW_RUNTIME_KAFKA_PASSWORD
EOF
chmod 600 "$OUT"
echo "wrote $OUT"
